@dataclass(frozen=True, slots=True)
class CompatibilityReport:
    """A live comparison between the registry and the pinned upstream inventory."""

    target_version: str
    target_commit: str
    upstream_count: int
    implemented: tuple[str, ...]
    missing: tuple[str, ...]
    unexpected: tuple[str, ...]

    @property
    def coverage(self) -> float:
        """Return operation-name coverage as a fraction between zero and one."""
        return len(self.implemented) / self.upstream_count

    @property
    def complete(self) -> bool:
        """Whether every pinned upstream operation is registered."""
        return not self.missing and not self.unexpected


def compatibility_report() -> CompatibilityReport:
    """Compare the current registry with CyberChef 11.3.0."""
    registered = set(registry.names())
    return CompatibilityReport(
        target_version=TARGET_CYBERCHEF_VERSION,
        target_commit=TARGET_CYBERCHEF_COMMIT,
        upstream_count=len(UPSTREAM_OPERATION_NAMES),
        implemented=tuple(sorted(registered & UPSTREAM_OPERATION_NAMES)),
        missing=tuple(sorted(UPSTREAM_OPERATION_NAMES - registered)),
        unexpected=tuple(sorted(registered - UPSTREAM_OPERATION_NAMES)),
    )
