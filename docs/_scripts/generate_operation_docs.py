@dataclass(frozen=True)
class PythonArgument:
    index: int
    name: str
    default: Any


def slug(name: str) -> str:
    value = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    return f"{value}_operation" if keyword.iskeyword(value) else value


def heading(title: str, marker: str = "=") -> str:
    # Git treats a line containing exactly seven equals signs as a conflict marker.
    return f"{title}\n{marker * max(len(title), 8)}\n\n"


def rst_text(value: object) -> str:
    text = str(value).replace("\n", " ")
    return re.sub(r"\s+", " ", text).strip() or "—"


def rst_description(value: object) -> str:
    """Keep upstream paragraphs and bullet lists readable in generated RST."""
    lines = [line.strip() for line in str(value).splitlines()]
    blocks: list[str] = []
    paragraph: list[str] = []

    def flush_paragraph() -> None:
        if paragraph:
            blocks.append(textwrap.fill(" ".join(paragraph), width=100))
            paragraph.clear()

    for line in lines:
        if not line:
            flush_paragraph()
        elif line.startswith(("- ", "* ")):
            flush_paragraph()
            blocks.append(textwrap.fill(line, width=100, subsequent_indent="  "))
        else:
            paragraph.append(line)
    flush_paragraph()
    return "\n\n".join(blocks) or "No upstream description is available."


def python_literal(value: Any) -> str:
    if isinstance(value, str) and value.startswith(("bytes(", "dict(", "list(")):
        return value
    return repr(value)


def safe_literal(node: ast.AST, module: Any) -> Any:
    try:
        return ast.literal_eval(node)
    except (ValueError, TypeError):
        if isinstance(node, ast.Name) and hasattr(module, node.id):
            value = getattr(module, node.id)
            if isinstance(value, (str, int, float, bool, bytes, type(None))):
                return value
        return ast.unparse(node)


def assignment_name(node: ast.Assign | ast.AnnAssign) -> str:
    target = node.target if isinstance(node, ast.AnnAssign) else node.targets[0]
    if isinstance(target, ast.Name):
        return target.id.replace("_", " ").title()
    return "Argument"


def python_arguments(implementation: Any) -> dict[int, PythonArgument]:
    """Discover positional args and defaults in an implementation and its helpers."""
    module = importlib.import_module(implementation.__module__)
    source = inspect.getsource(module)
    tree = ast.parse(source)
    functions = {node.name: node for node in tree.body if isinstance(node, ast.FunctionDef)}
    discovered: dict[int, PythonArgument] = {}
    visited: set[str] = set()

    def record(function_name: str, depth: int = 0) -> None:
        if function_name in visited or function_name not in functions or depth > 4:
            return
        visited.add(function_name)
        function = functions[function_name]
        for statement in ast.walk(function):
            if isinstance(statement, (ast.Assign, ast.AnnAssign)):
                name = assignment_name(statement)
                value = statement.value
                if value is None:
                    continue
                for call in (item for item in ast.walk(value) if isinstance(item, ast.Call)):
                    if (
                        isinstance(call.func, ast.Name)
                        and call.func.id == "arg"
                        and len(call.args) >= 2
                        and isinstance(call.args[0], ast.Name)
                        and call.args[0].id == "args"
                        and isinstance(call.args[1], ast.Constant)
                        and isinstance(call.args[1].value, int)
                    ):
                        index = call.args[1].value
                        default = safe_literal(call.args[2], module) if len(call.args) > 2 else None
                        discovered.setdefault(index, PythonArgument(index, name, default))
            if isinstance(statement, ast.Call) and isinstance(statement.func, ast.Name):
                called = statement.func.id
                if called.startswith("_"):
                    record(called, depth + 1)
            if (
                isinstance(statement, ast.Subscript)
                and isinstance(statement.value, ast.Name)
                and statement.value.id == "args"
                and isinstance(statement.slice, ast.Constant)
                and isinstance(statement.slice.value, int)
            ):
                index = statement.slice.value
                discovered.setdefault(index, PythonArgument(index, f"Argument {index}", None))

    record(implementation.__name__)
    return discovered


def load_metadata() -> dict[str, dict[str, Any]]:
    document = json.loads(DATA_FILE.read_text(encoding="utf-8"))
    if (
        document["version"] != TARGET_CYBERCHEF_VERSION
        or document["commit"] != TARGET_CYBERCHEF_COMMIT
    ):
        raise RuntimeError("operation metadata does not match the pinned CyberChef reference")
    return {item["name"]: item for item in document["operations"]}


def argument_rows(operation: Any, metadata: dict[str, Any]) -> list[dict[str, Any]]:
    module = importlib.import_module(operation.function.__module__)
    implementation = getattr(module, "_implementation", operation.function)
    local = python_arguments(implementation)
    upstream = {item["index"]: item for item in metadata.get("arguments", [])}
    rows: list[dict[str, Any]] = []
    indexes = sorted(set(local) | set(upstream))
    for index in indexes:
        upstream_item = upstream.get(index, {})
        local_item = local.get(index)
        default = local_item.default if local_item is not None else upstream_item.get("default")
        name = upstream_item.get("name") or (local_item.name if local_item else f"Argument {index}")
        choices = upstream_item.get("choices", [])
        toggles = upstream_item.get("toggle_values", [])
        accepted = choices or toggles
        if choices and default not in choices:
            default = upstream_item.get("default", choices[0])
        rows.append(
            {
                "index": index,
                "name": name,
                "type": upstream_item.get("type", "value"),
                "default": default,
                "accepted": accepted,
            }
        )
    return rows


def example_for(
    name: str, metadata: dict[str, Any], rows: list[dict[str, Any]]
) -> tuple[str, list[Any], str | None]:
    if name in CURATED_EXAMPLES:
        input_value, args, result = CURATED_EXAMPLES[name]
        return input_value, args, result
    input_type = metadata.get("input_type", "")
    input_value = 'b"example"' if input_type in {"ArrayBuffer", "byteArray"} else '"example"'
    args: list[Any] = []
    for row in rows:
        default = row["default"]
        if default is None:
            lowered = row["name"].lower()
            if "key" in lowered:
                default = {"string": "00112233445566778899aabbccddeeff", "option": "Hex"}
            elif row["accepted"]:
                default = row["accepted"][0]
            else:
                default = ""
        args.append(default)
    return input_value, args, None


def operation_page(operation: Any, metadata: dict[str, Any]) -> str:
    module_name = operation.function.__module__.rsplit(".", 1)[-1]
    rows = argument_rows(operation, metadata)
    input_value, args, expected = example_for(operation.name, metadata, rows)
    description = metadata.get("description") or f"Run the {operation.name} transformation."
    limitation = LIMITATIONS.get(operation.name)
    if limitation is None and operation.name.startswith(("PGP ", "Disassemble ")):
        limitation = "This operation currently implements a documented compatibility subset."

    parts = [GENERATED_NOTICE, heading(operation.name)]
    parts.append(f"**Category:** {operation.category or metadata.get('module') or 'Other'}\n\n")
    status = (
        "**Status:** Registered and callable in the "
        f"CyberChef {TARGET_CYBERCHEF_VERSION} compatibility inventory.\n\n"
    )
    parts.append(status)
    input_type = rst_text(metadata.get("input_type", "Data"))
    output_type = rst_text(metadata.get("output_type", "Data"))
    parts.append(f"**Input / output:** ``{input_type}`` → ``{output_type}``\n\n")
    if metadata.get("info_url"):
        parts.append(f"**Background:** `{metadata['info_url']} <{metadata['info_url']}>`_\n\n")
    parts.append(heading("What it does", "-"))
    parts.append(rst_description(description) + "\n\n")
    parts.append(
        ".. note::\n\n"
        "   Status here means the operation name is implemented and callable. It does not by\n"
        "   itself promise byte-for-byte parity for every upstream option. See\n"
        "   :doc:`../../compatibility` for the verified\n"
        "   scope and known boundaries.\n\n"
    )
    if limitation:
        parts.append(f".. warning::\n\n   {limitation}\n\n")

    parts.append(heading("Arguments and options", "-"))
    if not rows:
        parts.append("This operation takes no positional recipe arguments.\n\n")
    else:
        parts.append(
            "Arguments are positional. Keep their order when using ``bake()`` or\n"
            "``Pipeline.then()``.\n\n"
            ".. list-table::\n"
            "   :header-rows: 1\n"
            "   :widths: 8 24 16 24 28\n\n"
            "   * - Index\n"
            "     - Name\n"
            "     - UI type\n"
            "     - PyChef default\n"
            "     - Accepted values / format\n"
        )
        for row in rows:
            accepted = ", ".join(
                f"``{rst_text(python_literal(value))}``" for value in row["accepted"]
            )
            if not accepted:
                accepted = {
                    "boolean": "``True`` or ``False``",
                    "number": "A Python integer or floating-point value",
                    "string": "A Python string",
                    "text": "A Python string, including multi-line text",
                    "toggleString": 'A ``{"option": ..., "string": ...}`` mapping',
                }.get(row["type"], "Any value supported by this argument type")
            parts.append(
                f"   * - ``{row['index']}``\n"
                f"     - {rst_text(row['name'])}\n"
                f"     - ``{rst_text(row['type'])}``\n"
                f"     - ``{rst_text(python_literal(row['default']))}``\n"
                f"     - {accepted}\n"
            )
        parts.append("\n")

    args_literal = "[" + ", ".join(python_literal(value) for value in args) + "]"
    step = f'{{"op": {operation.name!r}, "args": args}}' if rows else repr(operation.name)
    curated_example = operation.name in CURATED_EXAMPLES
    parts.append(heading("Working recipe example" if curated_example else "Recipe template", "-"))
    if not curated_example:
        parts.append(
            ".. important::\n\n"
            "   This is a call template built from the documented defaults. Replace placeholder\n"
            "   values such as empty keys, paths, patterns, or lookup data before running it.\n\n"
        )
    parts.append(
        ".. code-block:: python\n\n"
        "   from pychef import bake\n\n"
        f"   input_value = {input_value}\n"
        f"   args = {args_literal}\n"
        f"   result = bake(input_value, [{step}])\n"
        "   print(result)\n\n"
    )
    if expected is not None:
        parts.append(f"Expected representation: ``{expected}``.\n\n")

    parts.append(heading("Pipeline example", "-"))
    then_args = ", *args" if rows else ""
    parts.append(
        ".. code-block:: python\n\n"
        "   from pychef import Pipeline\n\n"
        f"   args = {args_literal}\n"
        f"   transform = Pipeline().then({operation.name!r}{then_args})\n"
        f"   result = transform({input_value})\n\n"
    )
    parts.append(heading("Dedicated operation module", "-"))
    parts.append(
        "The registered entry point lives in\n"
        f"``pychef.operations.by_operation.{module_name}``. Direct calls\n"
        "receive the input value and a positional argument tuple:\n\n"
        ".. code-block:: python\n\n"
        f"   from pychef.operations.by_operation.{module_name} import run\n\n"
        f"   result = run({input_value}, tuple({args_literal}))\n\n"
        f".. autofunction:: pychef.operations.by_operation.{module_name}.run\n"
    )
    return "".join(parts)


def category_page(category: str, operations: list[Any]) -> str:
    parts = [GENERATED_NOTICE, heading(category)]
    parts.append(f"{len(operations)} registered operations are grouped in this category.\n\n")
    parts.append(".. toctree::\n   :hidden:\n   :maxdepth: 1\n\n")
    for operation in operations:
        parts.append(f"   ../reference/{slug(operation.name)}\n")
    parts.append("\n.. list-table::\n   :header-rows: 1\n   :widths: 50 20 30\n\n")
    parts.append("   * - Operation\n     - Status\n     - Module\n")
    for operation in operations:
        operation_slug = slug(operation.name)
        parts.append(
            f"   * - :doc:`{operation.name} <../reference/{operation_slug}>`\n"
            "     - callable\n"
            f"     - ``{operation.function.__module__}``\n"
        )
    return "".join(parts)


def operations_index(categories: dict[str, list[Any]]) -> str:
    operations = sorted(registry, key=lambda item: item.name.casefold())
    parts = [GENERATED_NOTICE, heading("Operation reference")]
    parts.append(
        f"PyChef registers {len(operations)} operation names from CyberChef "
        f"{TARGET_CYBERCHEF_VERSION}. Every operation has an individual page with positional "
        "options, status, recipe usage, pipeline usage, "
        "and its dedicated Python module.\n\n"
    )
    parts.append(".. toctree::\n   :hidden:\n   :maxdepth: 2\n\n")
    for category in sorted(categories, key=str.casefold):
        parts.append(f"   categories/{slug(category)}\n")
    parts.append("\nBrowse by category\n------------------\n\n")
    for category in sorted(categories, key=str.casefold):
        parts.append(
            f"* :doc:`{category} <categories/{slug(category)}>` ({len(categories[category])})\n"
        )
    parts.append("\nAll operations\n--------------\n\n")
    for operation in operations:
        parts.append(f"* :doc:`{operation.name} <reference/{slug(operation.name)}>`\n")
    return "".join(parts)


def expected_files() -> dict[Path, str]:
    metadata = load_metadata()
    registered_names = set(registry.names())
    missing_metadata = registered_names - set(metadata)
    if missing_metadata:
        raise RuntimeError(f"missing upstream metadata for: {sorted(missing_metadata)}")

    categories: dict[str, list[Any]] = defaultdict(list)
    files: dict[Path, str] = {}
    for operation in sorted(registry, key=lambda item: item.name.casefold()):
        category = operation.category or metadata[operation.name].get("module") or "Other"
        categories[category].append(operation)
        files[REFERENCE_DIR / f"{slug(operation.name)}.rst"] = operation_page(
            operation, metadata[operation.name]
        )
    for category, operations in categories.items():
        files[CATEGORY_DIR / f"{slug(category)}.rst"] = category_page(category, operations)
    files[DOCS / "operations" / "index.rst"] = operations_index(categories)
    return files


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated pages are stale")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    files = expected_files()
    stale: list[Path] = []
    for path, content in files.items():
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")

    expected_paths = set(files)
    existing_paths = set(REFERENCE_DIR.glob("*.rst")) | set(CATEGORY_DIR.glob("*.rst"))
    obsolete = sorted(existing_paths - expected_paths)
    if args.check and (stale or obsolete):
        names = ", ".join(str(path.relative_to(ROOT)) for path in stale + obsolete)
        raise SystemExit(f"generated operation documentation is stale: {names}")
    for path in obsolete:
        path.unlink()
    print(f"{'Checked' if args.check else 'Generated'} {len(files)} documentation files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
