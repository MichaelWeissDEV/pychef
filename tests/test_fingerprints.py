@pytest.mark.parametrize(("operation", "packet", "expected"), _OFFICIAL_CASES)
def test_fingerprint_official_vectors(operation: str, packet: str, expected: str) -> None:
    assert (
        bake(
            packet,
            [{"op": operation, "args": ["Hex", "Hash digest"]}],
        )
        == expected
    )


@pytest.mark.parametrize(
    ("operation", "string_format", "details_heading"),
    [
        ("HASSH Client Fingerprint", "HASSH algorithms string", "Full HASSH algorithms string:"),
        ("JA3 Fingerprint", "JA3 string", "Full JA3 string:"),
        ("JA3S Fingerprint", "JA3S string", "Full JA3S string:"),
    ],
)
def test_fingerprint_text_and_detail_formats(
    operation: str, string_format: str, details_heading: str
) -> None:
    case = next(case for case in _OFFICIAL_CASES if case.values[0] == operation)
    packet = case.values[1]
    assert isinstance(packet, str)
    fingerprint_string = bake(packet, [{"op": operation, "args": ["Hex", string_format]}])
    details = bake(packet, [{"op": operation, "args": ["Hex", "Full details"]}])
    assert isinstance(fingerprint_string, str)
    assert isinstance(details, str)
    assert details_heading in details
    assert fingerprint_string in details


def test_fingerprints_validate_packet_types_and_lengths() -> None:
    with pytest.raises(OperationError, match="Not handshake data"):
        bake("0000000000", [{"op": "JA3 Fingerprint", "args": ["Hex"]}])
    with pytest.raises(OperationError, match="Incorrect packet length"):
        bake("0000000214", [{"op": "HASSH Client Fingerprint", "args": ["Hex"]}])
