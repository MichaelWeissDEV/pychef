@pytest.mark.parametrize(("operation", "packet", "output_format", "expected"), _OFFICIAL_CASES)
def test_ja4_official_vectors(
    operation: str, packet: str, output_format: str, expected: str
) -> None:
    assert (
        bake(
            packet,
            [{"op": operation, "args": ["Hex", output_format]}],
        )
        == expected
    )


@pytest.mark.parametrize(
    ("operation", "output_format", "heading"),
    [
        ("JA4 Fingerprint", "All", "JA4_ro:"),
        ("JA4Server Fingerprint", "Both", "JA4S_r:"),
    ],
)
def test_ja4_combined_outputs(operation: str, output_format: str, heading: str) -> None:
    case = next(case for case in _OFFICIAL_CASES if case.values[0] == operation)
    packet = case.values[1]
    assert isinstance(packet, str)
    output = bake(packet, [{"op": operation, "args": ["Hex", output_format]}])
    assert isinstance(output, str)
    assert heading in output


def test_ja4_rejects_invalid_hello() -> None:
    with pytest.raises(OperationError, match="valid TLS Client Hello"):
        bake("0000000000", [{"op": "JA4 Fingerprint", "args": ["Hex", "JA4"]}])
    with pytest.raises(OperationError, match="valid TLS Server Hello"):
        bake("0000000000", [{"op": "JA4Server Fingerprint", "args": ["Hex", "JA4S"]}])
